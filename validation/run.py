"""
Run the validation benchmarks in OpenFOAM and write a report.

    source /usr/share/openfoam/etc/bashrc
    python -m validation.run                    # all benchmarks
    python -m validation.run --only cavity_ra1e5

Outputs (default ``docs/validation/``): one PNG per benchmark, ``results.json``
and ``results.md``.  Exit status is 1 if any metric is outside its tolerance.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from app.generators import GENERATORS
from app.postprocess import FoamCase
from validation.benchmarks import BENCHMARKS, Benchmark, Metric

REPO = Path(__file__).resolve().parent.parent


def _set_run_length(case_dir: Path, end_time: float) -> None:
    """Run for *end_time* and write the final state (and every 25 % of the run)."""
    cd = case_dir / "system" / "controlDict"
    text = cd.read_text()
    text = re.sub(r"^endTime\s+[^;]+;", f"endTime         {end_time:g};", text, flags=re.M)
    text = re.sub(r"^writeControl\s+[^;]+;", "writeControl    runTime;", text, flags=re.M)
    text = re.sub(r"^writeInterval\s+[^;]+;", f"writeInterval   {end_time / 4:g};", text, flags=re.M)
    cd.write_text(text)


def run_benchmark(b: Benchmark, work: Path) -> dict:
    case_dir = work / b.key
    shutil.rmtree(case_dir, ignore_errors=True)
    GENERATORS[b.solver]().generate(b.analysis, case_dir)
    _set_run_length(case_dir, b.end_time)

    t0 = time.time()
    proc = subprocess.run(["./Allrun"], cwd=case_dir, capture_output=True, text=True)
    elapsed = time.time() - t0
    if proc.returncode != 0:
        raise RuntimeError(f"{b.key}: Allrun failed\n{proc.stdout}\n{proc.stderr}")

    case = FoamCase(case_dir)
    log = (case_dir / f"log.{b.solver}").read_text(errors="replace")
    converged = re.search(r"converged in (\d+) iterations", log)
    metrics: list[Metric] = b.evaluate(case, b.analysis)
    return {
        "case": case,
        "metrics": metrics,
        "elapsed_s": elapsed,
        "cells": case.n_cells,
        "iterations": int(converged.group(1)) if converged else None,
        "final_time": case.latest_time(),
    }


def _fmt(x: float) -> str:
    return f"{x:.4g}"


def write_report(results: dict[str, dict], out_dir: Path) -> None:
    rows, data = [], {}
    for key, r in results.items():
        b = BENCHMARKS[key]
        data[key] = {
            "title": b.title, "description": b.description, "reference": b.reference,
            "solver": b.solver, "cells": r["cells"], "elapsed_s": round(r["elapsed_s"], 1),
            "converged_iterations": r["iterations"], "notes": b.notes,
            "metrics": [
                {"name": m.name, "value": float(m.value), "reference": float(m.reference),
                 "error": float(m.error), "tolerance": float(m.tolerance),
                 "passed": bool(m.passed), "source": m.source}
                for m in r["metrics"]
            ],
        }
        for m in r["metrics"]:
            rows.append(f"| {b.title} | {m.name} | {_fmt(m.value)} | {_fmt(m.reference)} | "
                        f"{m.error * 100:+.2f} % | ±{m.tolerance * 100:g} % | "
                        f"{'✅' if m.passed else '❌'} |")
    (out_dir / "results.json").write_text(json.dumps(data, indent=2))

    lines = [
        "# Validation results",
        "",
        "Generated by `python -m validation.run` (OpenFOAM v1912). Each case is produced by the",
        "normal generator from the analysis an LLM would return for the description below, run",
        "with its own `Allrun`, and post-processed in Python (`app/postprocess`).",
        "",
        "| Benchmark | Quantity | Generated case | Reference | Error | Tolerance | |",
        "|---|---|---:|---:|---:|---:|:-:|",
        *rows,
        "",
    ]
    for key, d in data.items():
        lines += [
            f"## {d['title']}",
            "",
            f"> {d['description']}",
            "",
            f"- **Solver:** `{d['solver']}` · **cells:** {d['cells']:,} · **run time:** {d['elapsed_s']:.0f} s"
            + (f" · converged in {d['converged_iterations']} iterations" if d["converged_iterations"] else ""),
            f"- **Reference:** {d['reference']}",
            *( [f"- **Notes:** {d['notes']}"] if d["notes"] else [] ),
            "",
            f"![{d['title']}]({key}.png)",
            "",
        ]
    (out_dir / "results.md").write_text("\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="*", choices=sorted(BENCHMARKS), help="benchmarks to run")
    ap.add_argument("--out", default=str(REPO / "docs" / "validation"), help="report directory")
    ap.add_argument("--workdir", help="where to keep the cases (default: temporary directory)")
    args = ap.parse_args(argv)

    if not shutil.which("blockMesh"):
        print("OpenFOAM not found: source your OpenFOAM etc/bashrc first.", file=sys.stderr)
        return 2

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    keys = args.only or list(BENCHMARKS)
    work_ctx = tempfile.TemporaryDirectory() if not args.workdir else None
    work = Path(args.workdir or work_ctx.name)
    work.mkdir(parents=True, exist_ok=True)

    results, all_passed = {}, True
    for key in keys:
        b = BENCHMARKS[key]
        print(f"▶ {b.title} …", flush=True)
        r = run_benchmark(b, work)
        b.plot(r["case"], b.analysis, r["metrics"], str(out_dir / f"{key}.png"))
        for m in r["metrics"]:
            all_passed &= m.passed
            print(f"   {'PASS' if m.passed else 'FAIL'}  {m.name}: {_fmt(m.value)} "
                  f"(ref {_fmt(m.reference)}, {m.error * 100:+.2f} %)")
        print(f"   {r['cells']:,} cells, {r['elapsed_s']:.0f} s")
        results[key] = r

    # Merge with previous results so running a subset keeps the others in the report
    previous = out_dir / "results.json"
    if args.only and previous.exists():
        old = json.loads(previous.read_text())
        merged = {k: v for k, v in old.items() if k not in results and k in BENCHMARKS}
        if merged:
            print("(keeping previous results for: " + ", ".join(merged) + ")")
            _write_merged(results, merged, out_dir)
        else:
            write_report(results, out_dir)
    else:
        write_report(results, out_dir)

    if work_ctx:
        work_ctx.cleanup()
    print("All benchmarks within tolerance." if all_passed else "Some metrics are OUTSIDE tolerance.")
    return 0 if all_passed else 1


def _write_merged(results: dict, old: dict, out_dir: Path) -> None:
    """Re-create Metric objects for benchmarks not re-run, then write one report."""
    class _Stub:
        pass
    full = {}
    for key in BENCHMARKS:
        if key in results:
            full[key] = results[key]
        elif key in old:
            d = old[key]
            full[key] = {
                "metrics": [Metric(m["name"], m["value"], m["reference"], m["tolerance"], "", m["source"])
                            for m in d["metrics"]],
                "elapsed_s": d["elapsed_s"], "cells": d["cells"],
                "iterations": d["converged_iterations"],
            }
    write_report(full, out_dir)


if __name__ == "__main__":
    sys.exit(main())
